exports.main = async () => {
  try {
    const prefix = 'cloud://job-cpti-dev-d6g8x3zkb2ae306f8.6a6f-job-cpti-dev-d6g8x3zkb2ae306f8-1457130836'

    const existing = await db.collection('cp_templates').limit(100).get()
    const existingKeys = new Set(existing.data.map(r => r.cpKey))
    const existingMap = new Map()
    existing.data.forEach(r => existingMap.set(r.cpKey, r))

    let added = 0, updated = 0

    const CHUNK = 8
    for (let i = 0; i < ALL_CP_DATA.length; i += CHUNK) {
      const batch = ALL_CP_DATA.slice(i, i + CHUNK)
      await Promise.all(batch.map(async ([cpKey, cpName, cpDescription, compatibilityScore, starLevel]) => {
        const [low, high] = cpKey.split('_').map(Number)
        const fileId = `${prefix}/cp/${cpKey}.jpg`

        if (!existingKeys.has(cpKey)) {
          await db.collection('cp_templates').add({
            data: {
              cpKey, lowPersonaId: low, highPersonaId: high,
              cpName, cpDescription, compatibilityScore, starLevel,
              shareImage: fileId
            }
          })
          added++
        } else {
          const old = existingMap.get(cpKey)
          if (!old.shareImage || old.shareImage !== fileId) {
            await db.collection('cp_templates').where({ cpKey })
              .update({ data: { shareImage: fileId } })
            updated++
          }
        }
      }))
    }

    return { code: 0, message: `补了 ${added} 条，更新 shareImage ${updated} 条`, added, updated }
  } catch (err) {
    return { code: 5000, message: err.message }
  }
}